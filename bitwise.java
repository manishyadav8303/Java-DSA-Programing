public class bitwise {
    public static void main(String[] args) {
        // and operator
        System.out.println(5&6);

        // or operator
        System.out.println(5|6);

        //  xor operator
        System.out.println(5^6);

        // ones comp
        System.out.println(~5);

        //left shift
        System.out.println(5<<2);

        //right shift
        System.out.println(6>>1);
    }
    
}
